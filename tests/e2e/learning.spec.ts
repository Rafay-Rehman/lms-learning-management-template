test('completing a lesson updates progress everywhere and survives a refresh', async ({ page }) => {
  await as(page, 'u-maya', '/learn/course/c-py-data/py-data-l9')
  const header = page.locator('header').getByText(/^\d+%$/)
  await expect(header).toHaveText('58%')
  await page.getByRole('button', { name: 'Mark as complete' }).click()
  await expect(page.getByText('Completed', { exact: true })).toBeVisible()
  await expect(header).toHaveText('67%')
  // The next incomplete lesson is suggested.
  await expect(page.getByRole('link', { name: /Next incomplete lesson.*Worksheet/ })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Completed', { exact: true })).toBeVisible()
  await expect(header).toHaveText('67%')
  // Reopening a completed lesson keeps it completed; the dashboard card agrees.
  await page.goto('/learn/course/c-py-data/py-data-l2')
  await expect(page.getByText('Completed', { exact: true })).toBeVisible()
  await page.goto('/learn')
  await expect(main(page).locator('article', { hasText: 'Python for Data Analysis' })).toContainText('67%')
})

