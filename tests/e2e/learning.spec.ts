test('visitor: landing → catalog search, filters, empty state → course details', async ({ page }) => {
  const errors = trackErrors(page)
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Learn something')
  await page.getByPlaceholder('What do you want to learn?').fill('python')
  await page.getByRole('button', { name: 'Browse courses' }).click()
  await expect(page).toHaveURL(/\/courses\?q=python/)
  const results = main(page).locator('article')
  await expect(results).toHaveCount(2)
  await page.getByLabel('Difficulty').selectOption('intermediate')
  await expect(page.getByText('No courses match')).toBeVisible()
  await page.getByRole('button', { name: 'Reset search and filters' }).click()
  await expect(page.getByText('14 courses')).toBeVisible()
  await page.getByLabel('Category').selectOption({ label: 'Mathematics' })
  await expect(results).toHaveCount(2)
  await page.getByLabel('Sort by').selectOption('title')
  await expect(results.first()).toContainText('Calculus I')
  await results.first().getByRole('link').click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Calculus I: Limits and Derivatives')
  await expect(page.getByText('What you’ll learn')).toBeVisible()
  await page.getByRole('button', { name: 'Preview' }).first().click()
  await expect(page.getByRole('dialog', { name: /Preview:/ })).toContainText('Video placeholder')
  expect(errors).toEqual([])
})

