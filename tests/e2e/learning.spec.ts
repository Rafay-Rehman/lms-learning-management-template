test('attempt limits are enforced and written answers wait for the instructor', async ({ page }) => {
  await as(page, 'u-maya', '/learn/quizzes/q-stats-exam')
  await expect(page.getByText('0 used of 1')).toBeVisible()
  await page.getByRole('button', { name: 'Start quiz' }).click()
  await expect(page.getByRole('timer')).toContainText('left')
  await page.getByLabel('The method captures the true value in 95% of repeated samples').check()
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Next' }).click()
  await page.getByLabel('Your answer').fill('Statistical significance says an effect is unlikely to be chance; practical significance asks whether it matters.')
  await page.getByRole('button', { name: 'Submit quiz' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Submit quiz' }).click()
  await expect(page.getByText('Waiting for grading')).toBeVisible()
  await page.goto('/learn/quizzes/q-stats-exam')
  await expect(page.getByText('You’ve used all 1 attempt')).toBeVisible()
  await expect(page.getByRole('button', { name: /Start/ })).toHaveCount(0)

  // The instructor grades the written answer; the result becomes final.
  await as(page, 'u-adeyemi', '/teach/grades?status=pending')
  await page.getByRole('row', { name: /Maya Patel.*Statistics midterm/ }).click()
  const drawer = page.getByRole('dialog', { name: 'Statistics midterm exam' })
  await drawer.getByRole('spinbutton').fill('3')
  await drawer.getByRole('button', { name: 'Save grades' }).click()
  await expect(page.getByText('Grades saved')).toBeVisible()
  const d = await stored(page)
  const attempt = d.attempts.find((a: { userId: string; quizId: string }) => a.userId === 'u-maya' && a.quizId === 'q-stats-exam')
  expect(attempt.status).toBe('graded')
  expect(attempt.manualPoints).toEqual({ 'q-stats-exam-q4': 3 })
})

test('finishing every required lesson issues one certificate that verifies', async ({ page }) => {
  await as(page, 'u-maya', '/learn/explore/acad-write')
  await page.getByRole('button', { name: 'Enroll for free' }).click()
  await expect(page).toHaveURL(/acad-write-l1$/)
  for (let i = 0; i < 6; i++) {
    const mark = page.getByRole('button', { name: 'Mark as complete' })
    if (await mark.isVisible()) await mark.click()
    const next = page.getByRole('link', { name: 'Next' })
    if (!(await next.isVisible())) break
    await next.click()
  }
  await expect(page.getByText('You’ve completed this course.')).toBeVisible()
  await page.goto('/learn/certificates')
  const card = main(page).locator('article', { hasText: 'Academic Writing and Research' })
  await expect(card).toContainText('Valid')
  const code = (await card.getByText(/LCT-/).textContent())!.match(/LCT-[A-Z0-9]{4}-[A-Z0-9]{4}/)![0]
  await card.getByRole('link', { name: 'Verify' }).click()
  await expect(page.getByText('Valid certificate')).toBeVisible()
  await expect(page.getByText(`Certificate ID ${code}`)).toBeVisible()
  const d = await stored(page)
  const e = d.enrollments.find((x: { userId: string; courseId: string }) => x.userId === 'u-maya' && x.courseId === 'c-acad-write')
  expect(e.status).toBe('completed')
  expect(d.certificates.filter((c: { enrollmentId: string }) => c.enrollmentId === e.id)).toHaveLength(1)
})

