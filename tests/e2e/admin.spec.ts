test('instructor creates a course: validation, curriculum, review, then admin publishes it', async ({ page }) => {
  const errors = trackErrors(page)
  await as(page, 'u-reyes', '/teach/builder')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Enter a title of at least 4 characters').first()).toBeVisible()
  await page.getByLabel('Title').fill('Accessible Web Forms')
  await page.getByLabel('Short description').fill('Build forms everyone can complete, with clear labels and helpful errors.')
  await page.getByLabel('Full description').fill('A short, practical course on building accessible web forms: labelling, grouping, inline validation, error summaries and testing with a screen reader.')
  await page.getByLabel('Learning objectives 1', { exact: true }).fill('Label every input correctly')
  await page.getByRole('tab', { name: /Curriculum/ }).click()
  for (const title of ['Why forms fail', 'Labels and hints', 'Error messages that help']) {
    await page.getByRole('button', { name: 'Add lesson' }).click()
    const dlg = page.getByRole('dialog', { name: 'New lesson' })
    await dlg.getByLabel('Lesson title').fill(title)
    await dlg.getByRole('button', { name: 'Save lesson' }).click()
  }
  // Keyboard-accessible reordering.
  await page.getByRole('button', { name: 'Move Error messages that help up' }).click()
  await page.getByRole('button', { name: 'Save' }).first().click()
  await expect(page.getByText('Course created as a draft')).toBeVisible()
  await page.getByRole('tab', { name: 'Publication' }).click()
  await page.getByRole('button', { name: 'Submit for review' }).click()
  await expect(page.getByText('Sent to an administrator for review')).toBeVisible()
  // Not public while in review.
  await page.goto('/courses?q=accessible')
  await expect(page.getByText('No courses match')).toBeVisible()

  await as(page, 'u-whitfield', '/admin/courses?status=review')
  await page.getByRole('button', { name: 'Actions for Accessible Web Forms' }).click()
  await page.getByRole('menuitem', { name: 'Approve and publish' }).click()
  await expect(page.getByText('Accessible Web Forms published')).toBeVisible()
  await page.goto('/courses?q=accessible')
  await expect(main(page).locator('article')).toHaveCount(1)
  const d = await stored(page)
  const c = d.courses.find((x: { title: string }) => x.title === 'Accessible Web Forms')
  expect(c.sections[0].lessons.map((l: { title: string }) => l.title)).toEqual(['Why forms fail', 'Error messages that help', 'Labels and hints'])
  expect(errors).toEqual([])
})

