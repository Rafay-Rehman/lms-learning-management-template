test('theme: live color edit, invalid hex, preset + customize, save, refresh, discard and reset', async ({ page }) => {
  const errors = trackErrors(page)
  await as(page, 'u-whitfield', '/admin/theme')
  const primary = () => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--primary').trim())
  await page.getByRole('button', { name: /Emerald Academy/ }).click()
  await expect.poll(primary).toBe('#11735a')
  await page.getByRole('tab', { name: 'Colors' }).click()
  await page.locator('#primary-hex').fill('#zzz')
  await expect(page.getByText('Use a hex color like #3D41D6')).toBeVisible()
  expect(await primary()).toBe('#11735a')
  await page.locator('#primary-hex').fill('#c2185b')
  await expect.poll(primary).toBe('#c2185b')
  await expect(page.getByText('Unsaved changes')).toBeVisible()
  // Dark palette preview.
  await page.getByRole('radio', { name: 'Preview dark' }).click()
  await expect(page.locator('.theme-scope')).toHaveClass(/dark/)
  await page.getByRole('button', { name: 'Save theme' }).click()
  await expect(page.getByText('Theme saved')).toBeVisible()
  await page.reload()
  await expect.poll(primary).toBe('#c2185b')
  await page.goto('/learn/explore')
  await expect.poll(primary).toBe('#c2185b')

  await page.goto('/admin/theme')
  await page.getByRole('tab', { name: 'Colors' }).click()
  await page.locator('#primary-hex').fill('#000000')
  await page.getByRole('button', { name: 'Discard changes' }).click()
  await expect.poll(primary).toBe('#c2185b')

  await page.getByRole('button', { name: 'Reset to defaults' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Reset to defaults' }).click()
  await page.getByRole('button', { name: 'Save theme' }).click()
  await expect.poll(primary).toBe('#3d41d6')
  expect((await stored(page)).theme.presetId).toBe('modern-indigo')
  expect(errors).toEqual([])
})

