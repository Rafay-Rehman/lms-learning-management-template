test('enrollment management: duplicates are rejected, suspended students drop out of active totals, CSV exports', async ({ page }) => {
  await as(page, 'u-okafor', '/teach/students')
  await page.getByRole('button', { name: 'Enroll a student' }).click()
  const dlg = page.getByRole('dialog', { name: 'Enroll a student' })
  await dlg.getByLabel('Student').selectOption({ label: 'Maya Patel' })
  await dlg.getByLabel('Course').selectOption({ label: 'Python for Data Analysis' })
  await dlg.getByRole('button', { name: 'Enroll' }).click()
  await expect(dlg.getByText('Maya Patel is already enrolled in this course')).toBeVisible()
  await dlg.getByRole('button', { name: 'Cancel' }).click()

  const activeCard = main(page).getByRole('button', { name: /^Active/ })
  const before = Number((await activeCard.locator('.numeral').textContent())!)
  await page.getByLabel('Search students').fill('Maya')
  await page.getByRole('button', { name: 'Actions for Maya Patel' }).first().click()
  await page.getByRole('menuitem', { name: 'Suspend' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Suspend' }).click()
  await expect(page.getByText('Enrollment suspended')).toBeVisible()
  await expect(activeCard.locator('.numeral')).toHaveText(String(before - 1))

  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  const file = await download
  expect(file.suggestedFilename()).toBe('enrollments.csv')
  const text = await (await file.createReadStream()).toArray().then((c) => Buffer.concat(c).toString('utf8'))
  expect(text).toContain('Student,Email,Course,Status')
  expect(text).toContain('suspended')
})

test('instructor dashboard metrics agree with the enrollment page', async ({ page }) => {
  await as(page, 'u-okafor', '/teach')
  const d = await stored(page)
  const mine = new Set(d.courses.filter((c: { instructorId: string }) => c.instructorId === 'u-okafor').map((c: { id: string }) => c.id))
  const enrolled = d.enrollments.filter((e: { courseId: string; status: string }) => mine.has(e.courseId) && ['active', 'completed'].includes(e.status))
  await expect(main(page).getByRole('link', { name: /Enrolled students/ })).toContainText(`${enrolled.length} enrollments`)
  await main(page).getByRole('link', { name: /Enrolled students/ }).click()
  await expect(page).toHaveURL(/\/teach\/students$/)
  const active = enrolled.filter((e: { status: string }) => e.status === 'active').length
  await expect(main(page).getByRole('button', { name: /^Active/ }).locator('.numeral')).toHaveText(String(active))
})
